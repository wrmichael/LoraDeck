# Builds main/audiowide.h: the Audiowide subset (assets/audiowide_call.ttf, SIL OFL 1.1, the web page's callsign
# font) as a smoothed bitmap for the Cardputer's LCD: 4 bits of coverage per pixel, one fixed height.
# Run: python3 tools/make_audiowide.py   (only needed when the font or the height changes)
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
TTF = root / 'assets/audiowide_call.ttf'
H = 30                                      # pixel rows of every glyph (the status screen's title band)
CHARS = ' -/0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'

# the largest size whose tallest and deepest glyphs fit in H rows
size = 40
while True:
    f = ImageFont.truetype(str(TTF), size)
    asc, desc = f.getmetrics()
    top = min(f.getbbox(c)[1] for c in CHARS if c != ' ')
    bot = max(f.getbbox(c)[3] for c in CHARS if c != ' ')
    if bot - top <= H:
        break
    size -= 1

glyphs, data = [], []
for c in CHARS:
    w = max(1, round(f.getlength(c)))
    im = Image.new('L', (w, H), 0)
    ImageDraw.Draw(im).text((0, -top), c, font=f, fill=255)
    px = im.load()
    start = len(data)
    nib = []
    for y in range(H):
        for x in range(w):
            nib.append(px[x, y] * 15 // 255)
    if len(nib) % 2:
        nib.append(0)
    data += [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]
    glyphs.append((c, w, start))

out = root / 'main/audiowide.h'
with open(out, 'w') as o:
    o.write('// Audiowide (SIL Open Font Licence 1.1, assets/audiowide_call.ttf) as a %d-pixel-high bitmap, 4 bits of\n'
            '// coverage per pixel, rows of each glyph one after the other. Generated by tools/make_audiowide.py.\n' % H)
    o.write('#pragma once\n#include <stdint.h>\n')
    o.write('static const int kAwHeight = %d;\n' % H)
    o.write('static const char kAwChars[] = "%s";\n' % CHARS)
    o.write('struct AwGlyph { uint8_t w; uint16_t off; };\n')
    o.write('static const AwGlyph kAwGlyphs[%d] = {\n' % len(glyphs))
    for c, w, s in glyphs:
        o.write('    {%d, %d},  // %r\n' % (w, s, c))
    o.write('};\nstatic const uint8_t kAwData[%d] = {\n' % len(data))
    for i in range(0, len(data), 24):
        o.write('    ' + ','.join('0x%02X' % b for b in data[i:i + 24]) + ',\n')
    o.write('};\n')
print('size', size, 'glyphs', len(glyphs), 'bytes', len(data))
