# Builds main/font6x8.h (ASCII 32-126, 6x8 cells, column bytes, LSB = top) from DejaVu Sans Mono.
import sys
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype(sys.argv[1], 9)
cols = []
for ch in range(32, 127):
    im = Image.new('L', (6, 8), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = '1'                     # no anti-aliasing: crisp on a 1-bit OLED
    d.text((0, -2), chr(ch), font=f, fill=255)
    px = im.load()
    for x in range(6):
        b = 0
        for y in range(8):
            if px[x, y] > 110: b |= 1 << y
        cols.append(b)
with open(sys.argv[2], 'w') as o:
    o.write('// 6x8 font, ASCII 32-126 (generated by tools/make_font.py from DejaVu Sans Mono, free licence).\n')
    o.write('#pragma once\n#include <stdint.h>\nstatic const uint8_t kFont6x8[95][6] = {\n')
    for i in range(95):
        o.write('    {' + ','.join('0x%02X' % c for c in cols[i*6:i*6+6]) + '},  // %r\n' % chr(32 + i))
    o.write('};\n')
